var updateExtractorFiles = flag.Bool("update", false, "rewrite extractor_files.txt")

// extractorFilesList is read by scripts/verify-maps-db.cjs: maps.db must be
// newer than the last change to these files. Only the code cmd/mapgen can
// reach belongs here. The 3D view, textures and character models also live
// in this package but only run inside the app, so editing them must not
// demand a maps.db regen.
const extractorFilesList = "extractor_files.txt"

// TestExtractorFiles recomputes which files cmd/mapgen reaches and fails if
// extractor_files.txt is out of date. Regenerate with:
//
//	go test ./internal/mapgen -run TestExtractorFiles -update
func TestExtractorFiles(t *testing.T) {
	got := reachableExtractorFiles(t)
	if *updateExtractorFiles {
		body := "# Files the maps.db extractor (cmd/mapgen) depends on, relative to\n" +
			"# backend/. Generated by TestExtractorFiles; read by\n" +
			"# scripts/verify-maps-db.cjs. Do not edit by hand:\n" +
			"#   go test ./internal/mapgen -run TestExtractorFiles -update\n" +
			strings.Join(got, "\n") + "\n"
		if err := os.WriteFile(extractorFilesList, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	raw, err := os.ReadFile(extractorFilesList)
	if err != nil {
		t.Fatalf("read %s: %v (run with -update)", extractorFilesList, err)
	}
	var want []string
	for _, l := range strings.Split(string(raw), "\n") {
		if l = strings.TrimSpace(l); l != "" && !strings.HasPrefix(l, "#") {
			want = append(want, l)
		}
	}
	if strings.Join(got, "\n") != strings.Join(want, "\n") {
		t.Fatalf("%s is out of date.\nwant:\n  %s\nhave:\n  %s\nRegenerate: go test ./internal/mapgen -run TestExtractorFiles -update",
			extractorFilesList, strings.Join(got, "\n  "), strings.Join(want, "\n  "))
	}
}

// reachableExtractorFiles type-checks this package and walks package-level
// references from the mapgen.X identifiers cmd/mapgen uses. Direct method
// calls resolve exactly; a method whose name matches an interface the
// package uses is reached with its type, so interface calls are covered. Returns paths
// relative to backend/, sorted: cmd/mapgen's files, the reached mapgen
// files, their build-tag twins and the files they //go:embed.
func reachableExtractorFiles(t *testing.T) []string {
	t.Helper()
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, ".", func(fi os.FileInfo) bool {
		return !strings.HasSuffix(fi.Name(), "_test.go")
	}, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}
	var files []*ast.File
	for _, f := range pkgs["mapgen"].Files {
		// Type-check only the files built for this OS; twins are added below.
		if !buildsHere(f) {
			continue
		}
		files = append(files, f)
	}
	info := &types.Info{Defs: map[*ast.Ident]types.Object{}, Uses: map[*ast.Ident]types.Object{}}
	// Only references inside this package matter, so an import the default
	// importer can't load (this module's own packages) is tolerated: the
	// checker keeps going and still resolves every in-package identifier.
	var typeErrs []string
	conf := &types.Config{
		Importer: importer.Default(),
		Error: func(err error) {
			if !strings.Contains(err.Error(), "could not import") {
				typeErrs = append(typeErrs, err.Error())
			}
		},
	}
	pkg, _ := conf.Check("mapgen", fset, files, info)
	if pkg == nil {
		t.Fatal("type-check produced no package")
	}
	// Uses of a failed import cascade into "undefined"/invalid-type errors;
	// those are expected. Anything mentioning neither is a real problem.
	for _, e := range typeErrs {
		if !strings.Contains(e, "enums") && !strings.Contains(e, "invalid") {
			t.Logf("type-check: %s", e)
		}
	}

	// Method names of every interface the package refers to, plus the ones
	// fmt and errors call implicitly.
	ifaceMethods := map[string]bool{"Error": true, "String": true, "GoString": true, "Format": true}
	for _, o := range info.Uses {
		tn, ok := o.(*types.TypeName)
		if !ok {
			continue
		}
		if it, ok := tn.Type().Underlying().(*types.Interface); ok {
			for i := 0; i < it.NumMethods(); i++ {
				ifaceMethods[it.Method(i).Name()] = true
			}
		}
	}

	// Edges: every package-level object (or method) to what its declaration
	// references in this package.
	edges := map[types.Object][]types.Object{}
	fileOf := map[types.Object]string{}
	addRefs := func(owner types.Object, n ast.Node) {
		ast.Inspect(n, func(n ast.Node) bool {
			id, ok := n.(*ast.Ident)
			if !ok {
				return true
			}
			if o := info.Uses[id]; o != nil && o.Pkg() == pkg && isTopLevel(o, pkg) {
				edges[owner] = append(edges[owner], o)
			}
			return true
		})
	}
	var inits []types.Object
	for _, f := range files {
		name := filepath.Base(fset.Position(f.Pos()).Filename)
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ast.FuncDecl:
				o := info.Defs[d.Name]
				fileOf[o] = name
				addRefs(o, d)
				if d.Recv == nil && d.Name.Name == "init" {
					inits = append(inits, o)
				}
				if d.Recv != nil && ifaceMethods[d.Name.Name] {
					// Direct calls resolve to the method itself. A method that
					// could be called through an interface (sort.Interface,
					// io.Reader, error, ...) is reached with its type.
					if tn := recvTypeName(info, d); tn != nil {
						edges[tn] = append(edges[tn], o)
					}
				}
			case *ast.GenDecl:
				for _, s := range d.Specs {
					switch s := s.(type) {
					case *ast.TypeSpec:
						o := info.Defs[s.Name]
						fileOf[o] = name
						addRefs(o, s)
					case *ast.ValueSpec:
						for _, id := range s.Names {
							o := info.Defs[id]
							if o == nil {
								continue
							}
							fileOf[o] = name
							addRefs(o, s)
						}
					}
				}
			}
		}
	}

	// Roots: package init funcs and every mapgen.X cmd/mapgen mentions.
	queue := append([]types.Object(nil), inits...)
	cmdFiles, err := filepath.Glob("../../cmd/mapgen/*.go")
	if err != nil {
		t.Fatal(err)
	}
	var out []string
	for _, cf := range cmdFiles {
		if strings.HasSuffix(cf, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, cf, nil, 0)
		if err != nil {
			t.Fatal(err)
		}
		out = append(out, "cmd/mapgen/"+filepath.Base(cf))
		ast.Inspect(f, func(n ast.Node) bool {
			if sel, ok := n.(*ast.SelectorExpr); ok {
				if x, ok := sel.X.(*ast.Ident); ok && x.Name == "mapgen" {
					if o := pkg.Scope().Lookup(sel.Sel.Name); o != nil {
						queue = append(queue, o)
					} else {
						t.Errorf("cmd/mapgen uses mapgen.%s, not found in the package", sel.Sel.Name)
					}
				}
			}
			return true
		})
	}
	if len(queue) == len(inits) {
		t.Fatal("found no mapgen.X references in cmd/mapgen")
	}

	seen := map[types.Object]bool{}
	reached := map[string]bool{}
	for len(queue) > 0 {
		o := queue[len(queue)-1]
		queue = queue[:len(queue)-1]
		if seen[o] {
			continue
		}
		seen[o] = true
		if f := fileOf[o]; f != "" {
			reached[f] = true
		}
		queue = append(queue, edges[o]...)
	}

	// Build-tag twins (openshared_windows.go for openshared_other.go) and
	// embedded files.
	embedRe := regexp.MustCompile(`(?m)^//go:embed\s+(.+)$`)
	for name := range pkgs["mapgen"].Files {
		base := filepath.Base(name)
		if reached[base] {
			continue
		}
		if stem := twinStem(base); stem != "" {
			for r := range reached {
				if twinStem(r) == stem {
					reached[base] = true
					break
				}
			}
		}
	}
	for r := range copyKeys(reached) {
		src, err := os.ReadFile(r)
		if err != nil {
			t.Fatal(err)
		}
		for _, m := range embedRe.FindAllStringSubmatch(string(src), -1) {
			for _, pat := range strings.Fields(m[1]) {
				reached[pat] = true
			}
		}
	}
	for r := range reached {
		out = append(out, "internal/mapgen/"+r)
	}
	sort.Strings(out)
	return out
}

func isTopLevel(o types.Object, pkg *types.Package) bool {
	if f, ok := o.(*types.Func); ok {
		return f.Type().(*types.Signature).Recv() != nil || o.Parent() == pkg.Scope()
	}
	return o.Parent() == pkg.Scope()
}

func recvTypeName(info *types.Info, d *ast.FuncDecl) types.Object {
	e := d.Recv.List[0].Type
	if s, ok := e.(*ast.StarExpr); ok {
		e = s.X
	}
	if ix, ok := e.(*ast.IndexExpr); ok {
		e = ix.X
	}
	if id, ok := e.(*ast.Ident); ok {
		return info.Uses[id]
	}
	return nil
}

// buildsHere reports whether f's //go:build line (only GOOS forms are used in
// this package) allows the current platform.
func buildsHere(f *ast.File) bool {
	for _, cg := range f.Comments {
		for _, c := range cg.List {
			if !strings.HasPrefix(c.Text, "//go:build ") {
				continue
			}
			expr := strings.TrimSpace(strings.TrimPrefix(c.Text, "//go:build "))
			neg := strings.HasPrefix(expr, "!")
			goos := strings.TrimPrefix(expr, "!")
			return (goos == runtime.GOOS) != neg
		}
	}
	return true
}

// twinStem returns the shared stem of a per-OS file ("openshared" for
// openshared_windows.go / openshared_other.go), or "".
func twinStem(name string) string {
	for _, sfx := range []string{"_windows.go", "_other.go"} {
		if strings.HasSuffix(name, sfx) {
			return strings.TrimSuffix(name, sfx)
		}
	}
	return ""
}

func copyKeys(m map[string]bool) map[string]bool {
	c := make(map[string]bool, len(m))
	for k := range m {
		c[k] = true
	}
	return c
}
